export const getProductById = (id) => {
  return SPARE_PARTS_CATALOG.find(p => p.id === id || p._id === id || p.sku === id);
};

export const getProductsByCategory = (categorySlug) => {
  if (!categorySlug || categorySlug === 'all') return SPARE_PARTS_CATALOG;
  return SPARE_PARTS_CATALOG.filter(p => p.category === categorySlug || p.categorySlug === categorySlug);
};
